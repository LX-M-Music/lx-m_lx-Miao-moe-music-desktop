const { launch, route, settled, captureHidden } = require('./helpers/motion-fixture.cjs')

function makeWav() {
  const rate = 8000
  const buffer = Buffer.alloc(44 + rate * 90 * 2)
  buffer.write('RIFF', 0); buffer.writeUInt32LE(buffer.length - 8, 4); buffer.write('WAVEfmt ', 8)
  buffer.writeUInt32LE(16, 16); buffer.writeUInt16LE(1, 20); buffer.writeUInt16LE(1, 22)
  buffer.writeUInt32LE(rate, 24); buffer.writeUInt32LE(rate * 2, 28); buffer.writeUInt16LE(2, 32); buffer.writeUInt16LE(16, 34)
  buffer.write('data', 36); buffer.writeUInt32LE(buffer.length - 44, 40)
  const title = Buffer.from('Mini player fixture\0')
  const tags = Buffer.alloc(20 + title.length + title.length % 2)
  tags.write('LIST'); tags.writeUInt32LE(tags.length - 8, 4); tags.write('INFOINAM', 8)
  tags.writeUInt32LE(title.length, 16); title.copy(tags, 20)
  const tagged = Buffer.concat([buffer, tags]); tagged.writeUInt32LE(tagged.length - 8, 4)
  return tagged
}

test('native desktop lyrics and playback-only mini player operate and persist independently', { timeout: 120000 }, async t => {
  const profilePath = await fs.mkdtemp(path.join(os.tmpdir(), 'lx-independent-windows-'))
  console.log('Independent window evidence:', profilePath)
  const songs = await Promise.all(['#3c9b84', '#cb8067', '#5b72b3'].map(async(color, i) => {
    const filePath = path.join(profilePath, `track-${i}.wav`)
    await fs.writeFile(filePath, makeWav())
    await fs.writeFile(path.join(profilePath, `track-${i}.lrc`), '[00:00.00]晚风轻轻掠过海面\n[00:15.00]把日落留在你身边\n[00:30.00]沿着光慢慢向前')
    const picUrl = 'data:image/svg+xml,' + encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200"><rect width="200" height="200" fill="${color}"/><circle cx="130" cy="64" r="31" fill="#f8dda9"/></svg>`)
    return { id: `mini-${i}`, name: ['晚风与海', '蓝色时刻', '沿途的光'][i], singer: '迷你播放器测试', source: 'local', interval: '01:30', meta: { albumName: 'Evening Tide', filePath, ext: 'wav', picUrl } }
  }))
  let fixture = await launch({ hidden: true, profilePath, rendererPath: path.resolve('dist/index.html') })
  let { app, page } = fixture
  let mini, desktop
  const errors = []
  const label = key => page.evaluate(key => window.i18n.t(key), key)
  const update = values => page.evaluate(values => window.lxData.updateSetting(values), values)
  const getWindow = async isMini => {
    const matches = p => p.url().includes('lyric.html') && new URL(p.url()).searchParams.has('mini') === isMini
    const result = app.windows().find(matches) ?? await app.waitForEvent('window', { predicate: matches })
    result.setDefaultTimeout(7000)
    result.on('pageerror', error => errors.push(error.message))
    await result.locator(isMini ? '[data-mini-player]' : '.font-lrc').first().waitFor()
    return result
  }
  const button = async key => mini.getByRole('button', { name: await label(key), exact: true })
  const trackIs = async index => {
    await page.waitForFunction(id => window.lxData.musicInfo.id === id, songs[index].id)
    await mini.locator('h1').filter({ hasText: songs[index].name }).waitFor()
    await mini.waitForFunction(() => document.querySelector('.mini-cover img')?.naturalWidth > 0)
  }
  const nativeButton = async key => {
    await desktop.mouse.move(20, 20)
    return desktop.getByTitle(await label(key), { exact: true })
  }
  try {
    page.setDefaultTimeout(8000)
    await app.evaluate(({ screen }) => { screen.getCursorScreenPoint = () => ({ x: -10000, y: -10000 }) })
    await page.evaluate(songs => require('electron').ipcRenderer.invoke('player_list_data_overwire', { defaultList: [], loveList: songs, tempList: [], userList: [] }), songs)
    await route(page, '/list?id=love')
    await settled(page)
    await page.locator('[data-song-id="mini-0"] [data-music-cell="index"]').dblclick()
    await page.waitForFunction(() => !window.__lxPluginHost.player.getAudioElement().paused && window.__lxPluginHost.player.getDuration() > 0)
    await page.locator('#player').getByRole('button', { name: await label('player__mini_player_on'), exact: true }).click()
    mini = await getWindow(true)
    await page.locator('#player').getByRole('button', { name: await label('player__desktop_lyric_on') }).click()
    desktop = await getWindow(false)

    await t.test('separate entries open original lyrics and mini controls without lyric UI or messages', async() => {
      await trackIs(0)
      assert.match(await desktop.title(), /Desktop Lyrics/)
      assert.match(await mini.title(), /Mini Player/)
      assert.equal(await mini.locator('.mini-track-info p').textContent(), songs[0].singer)
      assert.match(await mini.locator('.mini-cover img').getAttribute('src'), /^data:image\/webp/)
      assert.equal(await mini.locator('.font-lrc, [data-mini-lyrics], .lyric-single-line').count(), 0)
      assert.equal(await desktop.locator('[data-mini-player], .mini-options').count(), 0)
      await mini.waitForFunction(() => Number(document.querySelector('.mini-progress input').max) >= 89)
      assert.match(await desktop.locator('.font-lrc').first().textContent(), /晚风/)
      await captureHidden(app, mini, path.join(profilePath, 'mini-player.png'))
      await desktop.mouse.move(-20, -20)
      await captureHidden(app, desktop, path.join(profilePath, 'desktop-lyrics-horizontal.png'))
    })

    await t.test('mini pause, seek, volume, mute and queue still control real playback', async() => {
      await (await button('player__pause')).click()
      await page.waitForFunction(() => window.__lxPluginHost.player.getAudioElement().paused)
      await mini.locator('.mini-progress input').evaluate(el => { el.value = '30'; el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })) })
      await page.waitForFunction(() => Math.abs(window.__lxPluginHost.player.getCurrentTime() - 30) < 1)
      await desktop.waitForFunction(() => document.querySelector('.line-content.active')?.textContent.includes('沿着光'))
      await mini.locator('.mini-volume input').evaluate(el => { el.value = '0.27'; el.dispatchEvent(new Event('input', { bubbles: true })) })
      await page.waitForFunction(() => Math.abs(window.__lxPluginHost.player.getAudioElement().volume - 0.27) < 0.001)
      await (await button('mini_player__mute')).click()
      await page.waitForFunction(() => window.__lxPluginHost.player.getAudioElement().muted)
      await (await button('mini_player__unmute')).click()
      await page.waitForFunction(() => !window.__lxPluginHost.player.getAudioElement().muted)
      await page.evaluate(() => { window.app_event.setVolume(0.64); window.app_event.setProgress(17) })
      await mini.waitForFunction(() => document.querySelector('.mini-volume input').value === '0.64' && document.querySelector('.mini-times span').textContent === '00:17')
      const firstCover = await mini.locator('.mini-cover img').getAttribute('src')
      await (await button('player__next')).click()
      await trackIs(1)
      await mini.waitForFunction(first => document.querySelector('.mini-cover img')?.src !== first, firstCover)
      await (await button('player__prev')).click()
      await trackIs(0)
      await (await button('player__pause')).click()
      await mini.locator('.mini-progress input').dispatchEvent('pointerdown')
      await (await button('player__next')).click()
      await trackIs(1)
      await mini.locator('.mini-progress input').evaluate(el => { el.value = '65'; el.dispatchEvent(new Event('change', { bubbles: true })) })
      assert(await page.evaluate(() => window.__lxPluginHost.player.getCurrentTime()) < 10, 'a seek for an old song is ignored')
      await (await button('player__pause')).click()
    })

    await t.test('original toolbar, vertical layout, lyric styles and hide options work independently', async() => {
      const fontBefore = await page.evaluate(() => window.lxData.appSetting['desktopLyric.style.fontSize'])
      await (await nativeButton('desktop_lyric__font_increase')).click()
      await page.waitForFunction(value => window.lxData.appSetting['desktopLyric.style.fontSize'] === value + 1, fontBefore)
      await (await nativeButton('desktop_lyric__opacity_decrease')).click()
      await page.waitForFunction(() => window.lxData.appSetting['desktopLyric.style.opacity'] === 85)
      await (await nativeButton('desktop_lyric__lrc_active_zoom_on')).click()
      await page.waitForFunction(() => window.lxData.appSetting['desktopLyric.style.isZoomActiveLrc'])
      await update({ 'desktopLyric.direction': 'vertical', 'desktopLyric.style.lyricPlayedColor': 'rgba(255, 180, 80, 1)', 'desktopLyric.pauseHide': true })
      await desktop.waitForFunction(() => getComputedStyle(document.querySelector('.line-content')).writingMode === 'vertical-rl')
      await desktop.waitForFunction(() => document.querySelector('#container').classList.contains('hide'))
      assert.equal(await mini.locator('#container').evaluate(el => getComputedStyle(el).opacity), '1')
      await update({ 'desktopLyric.pauseHide': false })
      await desktop.mouse.move(-20, -20)
      await desktop.waitForFunction(() => !document.querySelector('#container').classList.contains('hide'))
      await captureHidden(app, desktop, path.join(profilePath, 'desktop-lyrics-vertical.png'))
      await (await nativeButton('desktop_lyric__lock')).click()
      await desktop.waitForFunction(() => document.querySelector('#container').classList.contains('lock'))
      assert.equal(await mini.locator('#container').evaluate(el => el.classList.contains('lock')), false)
      await page.locator('#player').getByRole('button', { name: await label('player__desktop_lyric_off') }).click({ button: 'right' })
      await desktop.waitForFunction(() => !document.querySelector('#container').classList.contains('lock'))
    })

    await t.test('settings and options contain no mini lyric controls; unrelated appearance controls synchronize', async() => {
      await route(page, '/setting')
      await page.locator('[data-setting-tab="SettingDesktopLyric"]').click()
      await page.locator('#setting_desktop_lyric_enable').waitFor({ state: 'attached' })
      await page.locator('#setting_mini_player_enable').waitFor({ state: 'attached' })
      assert.equal(await page.locator('[data-setting-tab="SettingMiniPlayer"]').count(), 0)
      assert.equal(await page.locator('#setting_mini_player_enable').count(), 1)
      assert.equal(await page.locator('#setting_mini_player_single_line, #setting_mini_player_show_player').count(), 0)
      await mini.locator('.mini-header button[aria-controls="mini-options"]').click()
      await mini.locator('#mini-options').waitFor()
      assert.doesNotMatch(await mini.locator('#mini-options').innerText(), /歌词|歌詞|lyric/i)
      await mini.getByLabel(await label('mini_player__show_border'), { exact: true }).check()
      await page.waitForFunction(() => window.lxData.appSetting['miniPlayer.showBorder'] && document.querySelector('#setting_mini_player_show_border').checked)
      await mini.getByLabel(await label('mini_player__transparent'), { exact: true }).check()
      await mini.waitForFunction(() => getComputedStyle(document.querySelector('#background')).opacity === '0')
      assert.equal(await page.evaluate(() => window.lxData.appSetting['desktopLyric.style.opacity']), 85)
      await mini.locator('#mini-options').getByRole('button', { name: await label('close'), exact: true }).click()
      const opacityInput = page.locator('input[aria-labelledby="mini_player_background_opacity"]')
      await opacityInput.fill('37')
      await opacityInput.dispatchEvent('change')
      await page.waitForFunction(() => window.lxData.appSetting['miniPlayer.backgroundOpacity'] === 37)
      await mini.waitForFunction(() => getComputedStyle(document.querySelector('#background')).opacity === '0.37')
      await update({ 'miniPlayer.backgroundOpacity': 100, 'miniPlayer.showBorder': false, 'miniPlayer.isAlwaysOnTop': true })
      await page.waitForFunction(() => !document.querySelector('#setting_mini_player_transparent').checked && !document.querySelector('#setting_mini_player_show_border').checked && document.querySelector('#setting_mini_player_top').checked)
      assert.equal(await page.evaluate(() => window.lxData.appSetting['desktopLyric.isAlwaysOnTop']), false)
      await page.locator('label[for="setting_mini_player_enable"]').scrollIntoViewIfNeeded()
      await captureHidden(app, page, path.join(profilePath, 'independent-settings.png'))
    })

    await t.test('closing and reopening either window leaves the other window and message channel working', async() => {
      await (await button('mini_player__close')).click()
      await page.waitForFunction(() => !window.lxData.appSetting['miniPlayer.enable'] && window.lxData.appSetting['desktopLyric.enable'])
      assert.equal(desktop.isClosed(), false)
      await (await nativeButton('desktop_lyric__font_increase')).click()
      await update({ 'miniPlayer.enable': true })
      mini = await getWindow(true)
      await trackIs(1)
      await (await nativeButton('desktop_lyric__close')).click()
      await page.waitForFunction(() => !window.lxData.appSetting['desktopLyric.enable'] && window.lxData.appSetting['miniPlayer.enable'])
      assert.equal(mini.isClosed(), false)
      await (await button('player__play')).click()
      await page.waitForFunction(() => !window.__lxPluginHost.player.getAudioElement().paused)
      await (await button('player__pause')).click()
      await update({ 'desktopLyric.enable': true })
      desktop = await getWindow(false)
      await page.waitForTimeout(700)
      assert.deepEqual(fixture.errors, [])
      await app.close()
      fixture = await launch({ hidden: true, profilePath, rendererPath: path.resolve('dist/index.html') })
      ;({ app, page } = fixture)
      mini = await getWindow(true)
      // Restored playback is stopped, so the native renderer may show its default welcome lyric.
      desktop = app.windows().find(p => p.url().includes('lyric.html') && !new URL(p.url()).searchParams.has('mini'))
      assert(desktop)
      await desktop.locator('#container').waitFor()
      assert.deepEqual(await page.evaluate(() => ['desktopLyric.enable', 'miniPlayer.enable', 'desktopLyric.direction', 'miniPlayer.isAlwaysOnTop'].map(key => window.lxData.appSetting[key])), [true, true, 'vertical', true])
      assert.equal(await mini.locator('.font-lrc, [data-mini-lyrics]').count(), 0)
      assert.equal(await page.evaluate(() => Object.hasOwn(window.lxData.appSetting, 'desktopLyric.singleLine')), false)
    })
    assert.deepEqual(errors, [])
    assert.deepEqual(fixture.errors, [])
  } finally { await app.close() }
})
