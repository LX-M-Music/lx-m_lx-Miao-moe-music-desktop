const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { test } = require('node:test')
const NodeID3 = require('node-id3')
const { launch, route } = require('./helpers/motion-fixture.cjs')
const { mp3, flac } = require('./helpers/tag-fixtures.cjs')
const { readTags } = require('../src/optional-plugins/audio-tag-editor/metadata')

const capture = async(fixture, filename) => {
  const window = await fixture.app.browserWindow(fixture.page)
  try {
    await window.evaluate(async window => { await window.capturePage(undefined, { stayHidden: true, stayAwake: true }) })
    await fixture.page.waitForTimeout(150)
    const bytes = await window.evaluate(async window => (await window.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG().toString('base64'))
    await fs.writeFile(filename, Buffer.from(bytes, 'base64'))
  } finally { await window.dispose() }
}
const invoke = (page, channel, params) => page.evaluate(({ channel, params }) => require('electron').ipcRenderer.invoke(channel, params), { channel, params })
const songs = (page, id) => invoke(page, 'player_list_music_get', id)

test('local song context menu edits MP3/FLAC files directly and refreshes persisted playlist metadata', { timeout: 120000 }, async t => {
  const rendererPath = path.resolve('dist/index.html')
  const output = path.resolve('output/playwright/local-music-tags')
  await fs.mkdir(output, { recursive: true })
  let fixture = await launch({ rendererPath, hidden: true, initializeMotion: false })
  const profilePath = fixture.output
  const mp3Path = path.join(profilePath, 'alpha.mp3'), flacPath = path.join(profilePath, 'beta.flac')
  const downloadPath = path.join(profilePath, 'download-regression.mp3')
  const mp3Fixture = mp3({ title: 'Alpha file title', artist: 'Original artist' })
  const flacFixture = flac(['TITLE=Beta file title', 'ARTIST=Original FLAC artist'])
  await fs.writeFile(mp3Path, mp3Fixture.bytes)
  await fs.writeFile(flacPath, flacFixture.bytes)
  await fs.writeFile(downloadPath, mp3({ title: 'Download original' }).bytes)
  const local = (id, name, filename) => ({ id, name, singer: 'Original artist', source: 'local', interval: '01:00', meta: { filePath: filename, ext: path.extname(filename).slice(1), songId: id, albumName: 'Original album' } })
  const alpha = local('alpha-row', 'Alpha song', mp3Path), beta = local('beta-row', 'Beta song', flacPath)
  const seed = [alpha, beta, local('missing-row', 'Missing song', path.join(profilePath, 'missing.mp3')), local('wav-row', 'Unsupported song', path.join(profilePath, 'unsupported.wav')),
    { id: 'online-row', name: 'Online song', singer: 'Online artist', source: 'wy', interval: '01:00', meta: { songId: 'online', albumName: 'Online album' } }]
  try {
    let { app, page } = fixture
    page.setDefaultTimeout(10000)
    await page.evaluate(() => Object.assign(window.lxData.appSetting, { 'common.isShowAnimation': false, 'list.isShowSource': true, 'list.actionButtonsVisible': false }))
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async() => { throw Error('The selected local song must open without another picker') } })
    await invoke(page, 'player_list_data_overwire', { defaultList: [], loveList: [alpha], tempList: [], userList: [{ id: 'tag-list', name: '本地标签测试', locationUpdateTime: null, list: seed }] })
    await route(page, '/list?id=tag-list')
    const row = id => page.locator(`#my-list .list-item[data-song-id="${id}"]`)
    const editor = page.locator('[data-audio-tag-editor]')
    const menu = () => page.getByRole('tab', { name: '修改音频标签', exact: true })
    const close = async() => { await editor.getByLabel('标题', { exact: true }).press('Escape'); await editor.waitFor({ state: 'hidden' }) }
    const open = async(id, title) => {
      await row(id).click({ button: 'right' })
      await menu().click()
      await editor.waitFor()
      await page.waitForFunction(title => document.querySelector('[data-audio-tag-editor] form input')?.value === title, title)
      assert(page.url().includes('/list?'), 'Editing must stay on the song playlist')
      assert.equal(await page.getByRole('dialog', { name: '修改音频标签', exact: true }).count(), 1)
    }
    await row('alpha-row').waitFor()
    assert.equal((await row('alpha-row').locator('.label-source').innerText()).trim(), 'local')
    await row('alpha-row').click({ button: 'right' })
    await menu().waitFor()
    assert.equal(await menu().getAttribute('disabled'), null)
    await capture(fixture, path.join(output, 'local-menu.png'))
    await menu().click()
    await page.waitForFunction(() => document.querySelector('[data-audio-tag-editor] form input')?.value === 'Alpha file title')
    assert((await editor.innerText()).includes(mp3Path))
    await capture(fixture, path.join(output, 'local-editor.png'))
    await editor.getByLabel('标题', { exact: true }).fill('修改后的本地歌曲')
    await editor.getByLabel('艺术家', { exact: true }).fill('修改后的歌手')
    await editor.getByLabel('专辑', { exact: true }).fill('修改后的专辑')
    await editor.getByLabel('年份 / 日期', { exact: true }).fill('2026')
    await editor.getByRole('button', { name: '保存标签', exact: true }).click()
    await editor.getByRole('status').filter({ hasText: '标签已保存到音频文件。' }).waitFor()
    const diskTags = NodeID3.read(await fs.readFile(mp3Path))
    assert.equal(diskTags.title, '修改后的本地歌曲')
    assert.equal(diskTags.artist, '修改后的歌手')
    assert.equal(diskTags.album, '修改后的专辑')
    assert((await fs.readFile(mp3Path)).subarray(-mp3Fixture.audio.length).equals(mp3Fixture.audio))
    for (const listId of ['tag-list', 'love']) {
      const updated = (await songs(page, listId)).find(song => song.id === 'alpha-row')
      assert.equal(updated.name, '修改后的本地歌曲')
      assert.equal(updated.singer, '修改后的歌手')
      assert.equal(updated.meta.albumName, '修改后的专辑')
      assert.equal(updated.meta.filePath, mp3Path)
      assert.equal(updated.meta.year, 2026)
    }
    await close()
    await row('alpha-row').getByText('修改后的本地歌曲', { exact: true }).waitFor()
    await open('alpha-row', '修改后的本地歌曲')
    await editor.getByLabel('标题', { exact: true }).fill('未保存草稿')
    await close()
    await open('alpha-row', '未保存草稿')
    await editor.getByRole('button', { name: '还原修改', exact: true }).click()
    await close()

    await page.evaluate(() => { window.lxData.appSetting['list.actionButtonsVisible'] = true })
    await row('beta-row').click({ button: 'right' })
    await menu().waitFor()
    await invoke(page, 'player_list_music_update_position', { listId: 'tag-list', position: 0, ids: ['beta-row'] })
    await menu().click()
    await page.waitForFunction(() => document.querySelector('[data-audio-tag-editor] form input')?.value === 'Beta file title')
    assert((await editor.innerText()).includes(flacPath), 'Reordering must preserve the right-click target')
    await editor.getByLabel('标题', { exact: true }).fill('修改后的 FLAC')
    await editor.getByRole('button', { name: '保存标签', exact: true }).click()
    await editor.getByRole('status').filter({ hasText: '标签已保存到音频文件。' }).waitFor()
    assert.equal((await readTags(flacPath)).tags.title, '修改后的 FLAC')
    assert((await fs.readFile(flacPath)).subarray(-flacFixture.audio.length).equals(flacFixture.audio))
    await close()
    await row('wav-row').click({ button: 'right' })
    assert.notEqual(await menu().getAttribute('disabled'), null)
    await page.keyboard.press('Escape')
    await row('online-row').click({ button: 'right' })
    assert.equal(await menu().count(), 0)
    await page.keyboard.press('Escape')
    await row('missing-row').click({ button: 'right' })
    await menu().click()
    await page.getByText('文件不存在或已移动，请重新选择文件。', { exact: false }).waitFor()
    const confirm = await page.evaluate(() => window.i18n.t('confirm_button_text'))
    await page.getByRole('button', { name: confirm, exact: true }).click()
    assert.equal(await editor.isVisible(), false)
    const beforeRestart = (await songs(page, 'tag-list')).map(song => song.id)
    assert.deepEqual(beforeRestart, ['beta-row', 'alpha-row', 'missing-row', 'wav-row', 'online-row'])
    // The existing Downloads entry uses the same shared modal after this change.
    const downloadTask = {
      id: 'download-regression', isComplate: true, status: 'completed', progress: 100, statusText: 'completed',
      metadata: { filePath: downloadPath, fileName: path.basename(downloadPath), quality: '128k', listId: 'default', musicInfo: local('download-regression', 'download-regression', downloadPath) },
    }
    await app.evaluate(({ ipcMain }, task) => {
      ipcMain.removeHandler('winMain_download_list_get')
      ipcMain.handle('winMain_download_list_get', () => [task])
    }, downloadTask)
    await page.evaluate(() => { window.lxData.appSetting['download.enable'] = true })
    await route(page, '/download')
    await page.locator('.list-item').filter({ hasText: 'download-regression' }).click({ button: 'right' })
    await menu().click()
    await page.waitForFunction(() => document.querySelector('[data-audio-tag-editor] form input')?.value === 'Download original')
    await editor.getByLabel('标题', { exact: true }).fill('Download shared editor')
    await editor.getByRole('button', { name: '保存标签', exact: true }).click()
    await editor.getByRole('status').filter({ hasText: '标签已保存到音频文件。' }).waitFor()
    assert.equal(NodeID3.read(await fs.readFile(downloadPath)).title, 'Download shared editor')
    await close()
    assert.deepEqual(fixture.errors, [])
    await app.close()

    fixture = await launch({ rendererPath, profilePath, hidden: true, initializeMotion: false })
    ;({ app, page } = fixture)
    page.setDefaultTimeout(10000)
    await route(page, '/list?id=tag-list')
    await page.locator('#my-list .list-item[data-song-id="alpha-row"]').getByText('修改后的本地歌曲', { exact: true }).waitFor()
    const restored = await songs(page, 'tag-list')
    assert.deepEqual(restored.map(song => song.id), beforeRestart)
    assert.equal(restored[0].name, '修改后的 FLAC')
    assert.equal(restored[1].meta.albumName, '修改后的专辑')
    assert.equal((await songs(page, 'love'))[0].name, '修改后的本地歌曲')
    assert.deepEqual(fixture.errors, [])
    await fs.writeFile(path.join(output, 'verification.json'), JSON.stringify({ directFileOpen: true, mp3Saved: true, flacSaved: true, audioBytesPreserved: true, playlistMetadataRefreshed: true, uncachedFavoriteUpdated: true, songIdsAndOrderPreserved: true, reorderedTargetPreserved: true, draftPreserved: true, unsupportedDisabled: true, onlineHidden: true, missingFileError: true, downloadsRegression: true, restart: true, errors: fixture.errors }, null, 2))
    t.diagnostic('Local music tag verification: ' + output)
  } catch (error) {
    await fs.writeFile(path.join(output, 'failure.txt'), await fixture.page.locator('body').innerText().catch(() => 'Page unavailable'))
    await capture(fixture, path.join(output, 'failure.png')).catch(() => {})
    t.diagnostic(JSON.stringify({ profilePath, errors: fixture.errors }))
    throw error
  } finally { await fixture.app.close().catch(() => {}) }
})
